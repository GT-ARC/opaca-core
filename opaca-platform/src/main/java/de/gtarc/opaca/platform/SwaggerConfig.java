package de.gtarc.opaca.platform;

import io.swagger.v3.oas.annotations.OpenAPIDefinition;
import io.swagger.v3.oas.annotations.enums.SecuritySchemeType;
import io.swagger.v3.oas.annotations.info.Info;
import io.swagger.v3.oas.annotations.security.SecurityScheme;
import io.swagger.v3.oas.annotations.security.SecuritySchemes;
import org.springdoc.core.models.GroupedOpenApi;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

@Configuration
@OpenAPIDefinition(info=@Info(
        title = "OPACA Runtime Platform",
        version = Application.VERSION,
        description = """
                Use this Web API to interact with the OPACA Runtime Platform and its Agent Containers. Here's a short
                description of the different groups of API routes:
                * **agents**: interact with agents inside the containers, e.g. by sending them messages, invoking actions
                * **authentication**: login to request an access token
                * **containers**: view, deploy or remove Agent Containers running on this platform
                * **connections**: view, add or remove other Runtime Platforms connected to this platform
                * **info**: get basic information on this Runtime Platform and its properties

                Complementary to the API docs generated by Swagger, an open-API compliant documentation for the currently available action can be found at [/v3/api-docs/actions](/v3/api-docs/actions) (or [/v3/api-docs/actions?format=YAML](/v3/api-docs/actions?format=YAML) for YAML). You can use the "?includeConnected=true" parameter to include actions from connected platforms, if any. Note that this route may require authorization.
                You can show and test available actions here in Swagger by selecting the definition "actions" above.
                
                The OPACA Platform also allows interaction via `/mcp` and `/a2a`. Select the respective definition to test them in Swagger.
                """
))
@SecuritySchemes({
        @SecurityScheme(
                name = "bearerAuth",
                type = SecuritySchemeType.HTTP,
                scheme = "bearer", 
                bearerFormat = "JWT"
        )
})
public class SwaggerConfig {

        private static final String[] AGENTS_PATHS = {
                "/.well-known/agent-card.json",
                "/a2a/**",
                "/mcp/**"
        };

        /**
         * This includes all the routes from /v3/api-docs except those that match the paths defined in AGENTS_PATHS,
         * i.e., all the routes belonging to the core OPACA API without having to list them all here.
         */
        @Bean
        GroupedOpenApi opaca() {
                return GroupedOpenApi.builder()
                        .group("opaca")
                        .displayName("1 - OPACA API")
                        .pathsToExclude(AGENTS_PATHS)
                        .build();
        }

        /**
         * This includes all the routes from /v3/api-docs that match the paths defined in AGENTS_PATHS, i.e., all the
         * "test" routes for A2A and MCP (not really supposed to be called by a human user or human-written program,
         * but useful for testing and visibility).
         */
        @Bean
        GroupedOpenApi agents() {
                return GroupedOpenApi.builder()
                        .group("agents")
                        .displayName("3 - MCP & A2A Support")
                        .pathsToMatch(AGENTS_PATHS)
                        .build();
        }

        /**
         * By using the group name "actions", this includes all the routes from /v3/api-docs/actions, i.e., all the
         * actions provided by the agents running on the platform. The "pathsToMatch" filter is redundant but required.
         */
        @Bean
        GroupedOpenApi actions() {
                return GroupedOpenApi.builder()
                        .group("actions")
                        .displayName("2 - OPACA Agent Actions")
                        .pathsToMatch("/invoke/**")
                        .build();
        }

}
